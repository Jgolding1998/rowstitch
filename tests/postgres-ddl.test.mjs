import test from 'node:test';
import assert from 'node:assert/strict';
import { column, defineTable } from '../dist/core/schema.js';
import { mappedCreateTableModel, mappedTableModel } from '../dist/core/model-mapping.js';
import { queryModel } from '../dist/core/query-model.js';
import { compilePostgresDDL, decodePostgresDDL, postgresDefaultLiteral } from '../dist/core/postgres-ddl.js';
import { snapshotPostgresResult } from '../dist/core/postgres-result.js';

const code = expected => error => error?.code === expected && !/SYNTHETIC_PRIVATE/.test(error.message);
const sample = defineTable('ddl_samples', {id: column.integer().primaryKey({generated: true}), exact: column.bigint().default(9223372036854775807n),
  ratio: column.real().default(-0), label: column.text().default("O'Reilly\\folder"), enabled: column.boolean().default(false), data: column.json().default({nested: [true, null]}), maybe: column.text().nullable().default(null)});
const ack = () => ({command: 'CREATE', rowCount: null, fields: [], rows: []});

test('creation uses qualified native types, BY DEFAULT identity, defaults and explicit primary keys', () => {
  const sql = compilePostgresDDL(mappedCreateTableModel(sample), 'sample');
  assert.match(sql, /^CREATE TABLE "sample"\."ddl_samples" /);
  assert.match(sql, /"id" "pg_catalog"\."int8" GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
  for (const type of ['int8', 'float8', 'text', 'bool', 'jsonb']) assert.ok(sql.includes('"pg_catalog"."' + type + '"'));
  assert.ok(sql.endsWith('PRIMARY KEY ("id"))'));
  assert.ok(!sql.includes('IF NOT EXISTS')); assert.ok(!sql.includes('ALTER TABLE'));
  assert.ok(sql.includes("E'9223372036854775807'::\"pg_catalog\".\"int8\""));
  assert.ok(sql.includes("E'-0'::\"pg_catalog\".\"float8\""));
  assert.ok(sql.includes('"maybe" "pg_catalog"."text" DEFAULT NULL'));
});

test('DEFAULT literals independently escape apostrophes and backslashes and preserve encoded JSON', () => {
  assert.equal(postgresDefaultLiteral('text', "quote' slash\\folder", false), "E'quote'' slash\\\\folder'::\"pg_catalog\".\"text\"");
  assert.equal(postgresDefaultLiteral('real', -0, false), "E'-0'::\"pg_catalog\".\"float8\"");
  assert.equal(postgresDefaultLiteral('boolean', 0, false), "E'false'::\"pg_catalog\".\"bool\"");
  assert.equal(postgresDefaultLiteral('integer', -2, false), "E'-2'::\"pg_catalog\".\"int8\"");
  assert.equal(postgresDefaultLiteral('text', null, true), 'NULL');
  const json = '{"path":"a\\\\b","quote":"O\'Reilly"}';
  assert.equal(postgresDefaultLiteral('json', json, false), "E'{\"path\":\"a\\\\\\\\b\",\"quote\":\"O''Reilly\"}'::\"pg_catalog\".\"jsonb\"");
  const injection = defineTable('safe_default', {id: column.integer().primaryKey(), label: column.text().default("');DROP TABLE sentinel;--\\tail")});
  const sql = compilePostgresDDL(mappedCreateTableModel(injection));
  assert.ok(sql.includes("DEFAULT E''');DROP TABLE sentinel;--\\\\tail'::\"pg_catalog\".\"text\""));
});

test('malformed direct default helper arguments fail with a constant VALIDATION error', () => {
  for (const kind of ['uuid', '__proto__', 'constructor', '', null, {}, 1]) assert.throws(() => postgresDefaultLiteral(kind, 1, false), code('VALIDATION'));
  for (const nullable of [undefined, 0, 1, 'false', null, {}]) assert.throws(() => postgresDefaultLiteral('integer', 1, nullable), code('VALIDATION'));
  for (const [kind, value] of [['text', '\ud800'], ['text', 'bad\0text'], ['text', {}], ['integer', 1n], ['integer', Number.MAX_SAFE_INTEGER + 1],
    ['bigint', 2n ** 63n], ['bigint', 1], ['real', NaN], ['real', Infinity], ['boolean', 1n], ['boolean', true], ['json', '{"x":1e999}'], ['json', '{"x":undefined}'], ['text', null]]) {
    assert.throws(() => postgresDefaultLiteral(kind, value, false), code('VALIDATION'));
  }
});

test('foreign references, mapped unique constraints and deterministic index statements are structured', () => {
  const parents = defineTable('ddl_parents', {id: column.integer().primaryKey()});
  const child = defineTable('ddl_children', {id: column.integer().primaryKey(), parent_id: column.integer().nullable().references(parents, 'id', {onDelete: 'set null'}), label: column.text().unique()});
  const sql = compilePostgresDDL(mappedCreateTableModel(child), 'sample');
  assert.ok(sql.includes('REFERENCES "sample"."ddl_parents" ("id") ON DELETE SET NULL'));
  assert.ok(sql.includes('"label" "pg_catalog"."text" NOT NULL UNIQUE'));
  const index = queryModel.createIndex({table: mappedTableModel(child), name: 'child_parent_idx', columns: ['parent_id']});
  assert.equal(compilePostgresDDL(index, 'sample'), 'CREATE INDEX "child_parent_idx" ON "sample"."ddl_children" ("parent_id")');
});

test('captured creation models compile without mutation; inconsistent metadata and generated defaults fail', () => {
  const source = structuredClone(mappedCreateTableModel(sample)), before = structuredClone(source);
  const sql = compilePostgresDDL(source); assert.deepEqual(source, before);
  source.definitions[3].defaultValue = 'caller changed'; assert.ok(!sql.includes('caller changed'));
  const mismatch = structuredClone(mappedCreateTableModel(sample)); mismatch.table.kinds.label = 'integer';
  assert.throws(() => compilePostgresDDL(mismatch), code('SCHEMA'));
  const both = defineTable('identity_default', {id: column.integer().default(1).primaryKey({generated: true})});
  assert.throws(() => compilePostgresDDL(mappedCreateTableModel(both)), code('SCHEMA'));
  for (const schema of ['pg_catalog', 'information_schema', "sample';DROP TABLE x;--", 'bad-name']) assert.throws(() => compilePostgresDDL(mappedCreateTableModel(sample), schema), code('SCHEMA'));
});

test('creation-model accessors, prototype tricks and Proxies cannot execute supplied code', () => {
  let calls = 0;
  const getter = {get() {calls++; throw new Error('SYNTHETIC_PRIVATE');}, enumerable: true};
  for (const change of [p => Object.defineProperty(p, 'definitions', getter), p => Object.defineProperty(p.definitions[0], 'kind', getter)]) {
    const source = structuredClone(mappedCreateTableModel(sample)); change(source); assert.throws(() => compilePostgresDDL(source), code('SCHEMA'));
  }
  const proxy = value => new Proxy(value, {get() {calls++; throw new Error('SYNTHETIC_PRIVATE');}, getPrototypeOf() {calls++; throw new Error('SYNTHETIC_PRIVATE');}, ownKeys() {calls++; throw new Error('SYNTHETIC_PRIVATE');}});
  assert.throws(() => compilePostgresDDL(proxy(mappedCreateTableModel(sample))), code('SCHEMA'));
  const nested = structuredClone(mappedCreateTableModel(sample)); nested.definitions = proxy(nested.definitions);
  assert.throws(() => compilePostgresDDL(nested), code('SCHEMA'));
  assert.throws(() => compilePostgresDDL(Object.create(mappedCreateTableModel(sample))), code('SCHEMA'));
  assert.equal(calls, 0);
});

test('DDL decoder accepts only an exact empty CREATE acknowledgment, not row query success', () => {
  assert.deepEqual(decodePostgresDDL(ack()), []); assert.deepEqual(decodePostgresDDL(snapshotPostgresResult(ack())), []);
  for (const change of [r => {r.command = 'SELECT';}, r => {r.command = 'CREATE TABLE';}, r => {r.rowCount = 0n;}, r => {r.rowCount = 1n;},
    r => {r.fields = [{name: 'x', typeOid: 20}];}, r => {r.rows = [[]];}, r => {delete r.command;}, r => {r.extra = true;}]) {
    const result = ack(); change(result); assert.throws(() => decodePostgresDDL(result), code('DATA'));
  }
  for (const result of [{...ack(), fields: [{name: 'unexpected', typeOid: 20}]}, {...ack(), rows: [[]]}, {...ack(), rowCount: 0n}]) {
    assert.throws(() => decodePostgresDDL(snapshotPostgresResult(result)), code('DATA'), 'A branded shape still needs the exact DDL contract.');
  }
});

test('DDL acknowledgment accessors and Proxies are refused before any supplied trap or getter', () => {
  let calls = 0;
  const result = ack(); Object.defineProperty(result, 'command', {get() {calls++; throw new Error('SYNTHETIC_PRIVATE');}, enumerable: true});
  assert.throws(() => decodePostgresDDL(result), code('DATA'));
  const proxy = value => new Proxy(value, {get() {calls++; throw new Error('SYNTHETIC_PRIVATE');}, getPrototypeOf() {calls++; throw new Error('SYNTHETIC_PRIVATE');}, ownKeys() {calls++; throw new Error('SYNTHETIC_PRIVATE');}});
  assert.throws(() => decodePostgresDDL(proxy(ack())), code('DATA'));
  for (const field of ['fields', 'rows']) {const result = ack(); result[field] = proxy([]); assert.throws(() => decodePostgresDDL(result), code('DATA'));}
  assert.equal(calls, 0);
});
